-- 로그인 세션(refresh token). 원문은 저장하지 않고 SHA-256 해시(hex)만 저장한다.
-- 재발급할 때마다 기존 토큰은 revoked_at 을 채우고 새 행을 만든다 (rotation).
-- DR 복제(CDC) 대상이 아니다: 장애 전환 후에는 다시 로그인하면 되고, 자격 증명(user_credential)은 복제된다.
CREATE TABLE users.refresh_token (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users.app_user(id),
  token_hash  CHAR(64) NOT NULL UNIQUE,
  expires_at  TIMESTAMPTZ NOT NULL,
  revoked_at  TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_refresh_token_user ON users.refresh_token (user_id);
