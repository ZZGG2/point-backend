-- 이 마이그레이션은 AWS Aurora와 GCP Cloud SQL 양쪽에 적용된다 (DDL은 CDC로 복제되지 않음)
CREATE SCHEMA IF NOT EXISTS users;
CREATE SCHEMA IF NOT EXISTS asset;
CREATE SCHEMA IF NOT EXISTS point;
CREATE SCHEMA IF NOT EXISTS cs;

CREATE TABLE users.app_user (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       VARCHAR(255) NOT NULL UNIQUE,
  name_enc    VARCHAR(512) NOT NULL,          -- 애플리케이션 레벨 암호화
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE users.user_credential (
  user_id        BIGINT PRIMARY KEY REFERENCES users.app_user(id),
  password_hash  VARCHAR(255) NOT NULL,
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE asset.linked_account (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL,
  institution  VARCHAR(50) NOT NULL,
  account_mask VARCHAR(50) NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE point.point_wallet (
  user_id     BIGINT PRIMARY KEY,
  balance     BIGINT NOT NULL CHECK (balance >= 0),
  version     BIGINT NOT NULL DEFAULT 0,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE point.point_ledger (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT NOT NULL,
  type             VARCHAR(20) NOT NULL,
  amount           BIGINT NOT NULL,
  balance_after    BIGINT NOT NULL,
  idempotency_key  VARCHAR(100) NOT NULL UNIQUE,
  source           VARCHAR(30) NOT NULL,
  reference_id     VARCHAR(100),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_ledger_user_created ON point.point_ledger (user_id, created_at DESC);

CREATE TABLE point.refund_request (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL,
  ledger_id    BIGINT NOT NULL REFERENCES point.point_ledger(id),
  status       VARCHAR(20) NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cs.notice (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(200) NOT NULL,
  body        TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- DR 복제 Lag(=RPO) 측정용. Debezium heartbeat.action.query 가 1초마다 갱신
CREATE TABLE public.dr_heartbeat (
  id  INT PRIMARY KEY,
  ts  TIMESTAMPTZ NOT NULL
);
